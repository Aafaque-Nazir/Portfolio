/**
 * Splits src/data/blogs.js into:
 * - src/data/blogs-meta.js (lightweight index metadata for CommandMenu, Blog list, prev/next & related posts)
 * - src/data/posts/<slug>.json (per-article payload loaded on demand by BlogPost.jsx)
 */

import fs from "fs";
import path from "path";
import process from "process";
import { fileURLToPath, pathToFileURL } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

export async function syncBlogData() {
  const blogsPath = path.join(rootDir, "src", "data", "blogs.js");
  const metaOutPath = path.join(rootDir, "src", "data", "blogs-meta.js");
  const postsDir = path.join(rootDir, "src", "data", "posts");

  const moduleUrl = `${pathToFileURL(blogsPath).href}?t=${Date.now()}`;
  const { blogs } = await import(moduleUrl);

  fs.mkdirSync(postsDir, { recursive: true });

  const expectedFiles = new Set();
  const metaList = blogs.map((post) => {
    const fileName = `${post.slug}.json`;
    expectedFiles.add(fileName);
    const postOutPath = path.join(postsDir, fileName);
    const serialized = `${JSON.stringify(post, null, 2)}\n`;
    if (!fs.existsSync(postOutPath) || fs.readFileSync(postOutPath, "utf8") !== serialized) {
      fs.writeFileSync(postOutPath, serialized, "utf8");
    }

    return {
      id: post.id,
      slug: post.slug,
      title: post.title,
      seoTitle: post.seoTitle,
      description: post.description,
      publishedAt: post.publishedAt,
      updatedAt: post.updatedAt,
      readTime: post.readTime,
      category: post.category,
      tags: post.tags || [],
      author: post.author,
      relatedProjectId: post.relatedProjectId,
    };
  });

  // Remove stale post JSON files if a post was deleted or renamed
  for (const existingFile of fs.readdirSync(postsDir)) {
    if (existingFile.endsWith(".json") && !expectedFiles.has(existingFile)) {
      fs.unlinkSync(path.join(postsDir, existingFile));
    }
  }

  const metaContent = `// Auto-generated by scripts/sync-blog-data.js from src/data/blogs.js\nexport const blogsMeta = ${JSON.stringify(metaList, null, 2)};\n`;
  if (!fs.existsSync(metaOutPath) || fs.readFileSync(metaOutPath, "utf8") !== metaContent) {
    fs.writeFileSync(metaOutPath, metaContent, "utf8");
  }

  console.log(`Synced ${metaList.length} blog metadata entries and per-post JSON chunks.`);
}

const isDirectRun = process.argv[1] && path.resolve(process.argv[1]) === __filename;
if (isDirectRun) {
  syncBlogData().catch((err) => {
    console.error("Failed to sync blog data:", err);
    process.exit(1);
  });
}
